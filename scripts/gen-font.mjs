import { readFileSync, writeFileSync } from "node:fs";

const [bdfPath, outPath] = process.argv.slice(2);
const lines = readFileSync(bdfPath, "utf8").split("\n");
const ascent = Number(lines.find((l) => l.startsWith("FONT_ASCENT"))?.split(" ")[1]);
const glyphs = [];
let code = -1;
let bbx = [8, 16, 0, -4];
let bitmap = null;
for (const line of lines) {
  const [word, ...rest] = line.trim().split(/\s+/);
  if (word === "ENCODING") code = Number(rest[0]);
  else if (word === "BBX") bbx = rest.map(Number);
  else if (word === "BITMAP") bitmap = [];
  else if (word === "ENDCHAR") {
    const [w, h, xoff, yoff] = bbx;
    if (code >= 0 && w <= 8) {
      const rows = new Uint8Array(16);
      const top = ascent - (yoff + h);
      bitmap.forEach((hex, i) => {
        const y = top + i;
        if (y >= 0 && y < 16) rows[y] = (Number.parseInt(hex, 16) >> xoff) & 0xff;
      });
      glyphs.push([code, Buffer.from(rows).toString("base64")]);
    }
    bitmap = null;
    code = -1;
  } else if (bitmap) bitmap.push(word);
}
const body = glyphs.map(([c, b]) => `${c}:"${b}"`).join(",");
writeFileSync(
  outPath,
  `// Generated by scripts/gen-font.mjs from Spleen 8x16 (BSD-2-Clause, Copyright (c) 2018-2026 Frederic Cambus).\nexport const GLYPHS: Record<number, string> = {${body}};\n`,
);
console.log(`${glyphs.length} glyphs`);
